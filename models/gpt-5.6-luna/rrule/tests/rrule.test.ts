import { describe, expect, it } from "vitest";
import { expandOccurrences } from "../src/rrule";

const madrid = "Europe/Madrid";

function isoValues(dates: Date[]): string[] {
  return dates.map((date) => date.toISOString());
}

describe("expandOccurrences", () => {
  it("keeps a weekly event at the same Madrid local time across October DST", () => {
    const start = new Date("2024-10-20T08:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=WEEKLY;BYDAY=SU",
      madrid,
      start,
      new Date("2024-11-04T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-10-20T08:00:00.000Z",
      "2024-10-27T09:00:00.000Z",
      "2024-11-03T09:00:00.000Z",
    ]);
  });

  it("applies DAILY INTERVAL using calendar days across DST", () => {
    const start = new Date("2024-10-25T08:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=DAILY;INTERVAL=2;COUNT=3",
      madrid,
      start,
      new Date("2024-11-01T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-10-25T08:00:00.000Z",
      "2024-10-27T09:00:00.000Z",
      "2024-10-29T09:00:00.000Z",
    ]);
  });

  it("expands the last Friday of each month", () => {
    const start = new Date("2024-01-01T09:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=MONTHLY;BYDAY=-1FR;COUNT=4",
      madrid,
      start,
      new Date("2024-05-01T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-01-26T09:00:00.000Z",
      "2024-02-23T09:00:00.000Z",
      "2024-03-29T09:00:00.000Z",
      "2024-04-26T08:00:00.000Z",
    ]);
  });

  it("skips months that do not contain DTSTART's day of month", () => {
    const start = new Date("2024-01-31T09:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=MONTHLY",
      madrid,
      start,
      new Date("2024-06-01T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-01-31T09:00:00.000Z",
      "2024-03-31T08:00:00.000Z",
      "2024-05-31T08:00:00.000Z",
    ]);
  });

  it("applies COUNT to all occurrences generated by BYDAY", () => {
    const start = new Date("2024-01-01T09:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=WEEKLY;BYDAY=MO,WE;COUNT=5",
      madrid,
      start,
      new Date("2024-01-20T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-01-01T09:00:00.000Z",
      "2024-01-03T09:00:00.000Z",
      "2024-01-08T09:00:00.000Z",
      "2024-01-10T09:00:00.000Z",
      "2024-01-15T09:00:00.000Z",
    ]);
  });

  it("supports positive monthly BYDAY ordinals", () => {
    const start = new Date("2024-01-01T09:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=MONTHLY;BYDAY=2TU;COUNT=3",
      madrid,
      start,
      new Date("2024-04-01T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-01-09T09:00:00.000Z",
      "2024-02-13T09:00:00.000Z",
      "2024-03-12T09:00:00.000Z",
    ]);
  });

  it("stops at an inclusive UNTIL", () => {
    const start = new Date("2024-01-01T09:00:00.000Z");
    const occurrences = expandOccurrences(
      start,
      "FREQ=DAILY;UNTIL=20240103T090000Z",
      madrid,
      start,
      new Date("2024-01-10T00:00:00.000Z"),
    );

    expect(isoValues(occurrences)).toEqual([
      "2024-01-01T09:00:00.000Z",
      "2024-01-02T09:00:00.000Z",
      "2024-01-03T09:00:00.000Z",
    ]);
  });
});
